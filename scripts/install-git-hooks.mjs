#!/usr/bin/env node
/**
 * Устанавливает локальные git-хуки без husky. Запускается автоматически после
 * `pnpm install` (через скрипт `prepare` в package.json).
 *
 * Зачем без husky: одна нативная зависимость меньше + полный контроль над тем,
 * что выполняется. В CI (где .git нет) аккуратно ничего не делаем.
 */
import { existsSync, mkdirSync, writeFileSync, chmodSync, readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const gitDir = resolve(repoRoot, ".git");

// В CI / npx-окружении / при установке как dependency .git может отсутствовать.
// Это не ошибка — просто пропускаем.
if (!existsSync(gitDir)) {
  process.exit(0);
}

const hooksDir = resolve(gitDir, "hooks");
if (!existsSync(hooksDir)) {
  mkdirSync(hooksDir, { recursive: true });
}

const preCommitPath = resolve(hooksDir, "pre-commit");

const PRE_COMMIT = `#!/usr/bin/env sh
# Generated by scripts/install-git-hooks.mjs — не редактируй вручную.
# Запускает lint-staged: eslint --fix на staged ts/tsx, prettier на остальное.
# Если хук тормозит — пропусти один коммит флагом --no-verify.

exec pnpm lint:staged
`;

// Не перезаписываем, если уже есть точно такой же контент — иначе timestamp
// меняется на каждый install и git думает что hook менялся.
let needsWrite = true;
if (existsSync(preCommitPath)) {
  const current = readFileSync(preCommitPath, "utf8");
  if (current === PRE_COMMIT) needsWrite = false;
}

if (needsWrite) {
  writeFileSync(preCommitPath, PRE_COMMIT, "utf8");
  chmodSync(preCommitPath, 0o755);
  console.log("[hooks] installed pre-commit");
} else {
  // тихо — не шумим в логе на каждом pnpm install.
}
